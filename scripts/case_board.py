"""Write a generated PCB's size and its hole, connector and LED positions to an OpenSCAD file for the case. Prints
the board's bottom left corner on the page, for kicad-cli's --user-origin. Run with KiCad's bundled Python.

Case coordinates are mm from the board's bottom left corner, y up, so ports 1 to 4 are on the y = 0 edge."""
import re
import sys

import pcbnew


def mm(v):
    return round(pcbnew.ToMM(v), 3)


def main(pcb, out):
    b = pcbnew.LoadBoard(pcb)
    edges = [d for d in b.GetDrawings() if d.GetLayer() == pcbnew.Edge_Cuts]
    points = [(mm(p.x), mm(p.y)) for d in edges if d.GetShape() == pcbnew.SHAPE_T_SEGMENT
              for p in (d.GetStart(), d.GetEnd())]
    left, top = (min(c) for c in zip(*points))
    right, bottom = (max(c) for c in zip(*points))
    radius = {mm(d.GetRadius()) for d in edges if d.GetShape() == pcbnew.SHAPE_T_ARC}
    if len(radius) != 1:
        sys.exit('board corners: expected one radius, found %s' % sorted(radius))

    def xy(f):
        p = f.GetPosition()
        return [round(mm(p.x) - left, 3), round(bottom - mm(p.y), 3)]

    holes, leds, ports, top_edge = [], [], {}, {}
    for f in b.GetFootprints():
        name = str(f.GetFPID().GetLibItemName())
        nets = {p.GetNetname() for p in f.Pads()}
        if name.startswith('MountingHole'):
            holes.append(xy(f))
        elif name.startswith('LED_'):
            leds.append(xy(f))
        elif name.startswith('USB_C_connector'):
            vbus = [re.fullmatch(r'/VBUS(\d)', n) for n in nets]
            vbus = [m for m in vbus if m]
            if vbus:
                ports[int(vbus[0].group(1))] = (f, xy(f)[0], 0)
            elif 'UP_VBUS' in nets:
                top_edge['host'] = (f, xy(f)[0], 180)
            elif 'EXT_5V' in nets:
                top_edge['power_in'] = (f, xy(f)[0], 180)
    if sorted(ports) != [1, 2, 3, 4] or sorted(top_edge) != ['host', 'power_in'] or len(holes) != 4:
        sys.exit('expected ports 1 to 4, HOST, 5V IN and 4 mounting holes')
    for f, _, angle in list(ports.values()) + list(top_edge.values()):
        if round(f.GetOrientationDegrees()) % 360 != angle:
            sys.exit('%s: expected at %d degrees, on its edge' % (f.GetReference(), angle))

    with open(out, 'w') as o:
        o.write('// Generated by scripts/case_board.py from %s\n' % pcb.split('/')[-1])
        o.write('board = [%g, %g];\n' % (right - left, bottom - top))
        o.write('board_r = %g;\n' % radius.pop())
        o.write('holes = %s;\n' % sorted(holes))
        o.write('ports = %s;\n' % [ports[n][1] for n in sorted(ports)])
        o.write('host = %g;\n' % top_edge['host'][1])
        o.write('power_in = %g;\n' % top_edge['power_in'][1])
        o.write('leds = %s;\n' % sorted(leds))
    print('%gx%gmm' % (left, bottom))


main(*sys.argv[1:])
